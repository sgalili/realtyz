export type RitaWorkflow = 'broker' | 'partner' | 'developer' | 'private';

export function ritaWorkflow(roles: readonly string[], partnerMode = false): RitaWorkflow {
  if (roles.includes('affiliate') && partnerMode) return 'partner';
  if (roles.includes('developer') && !roles.includes('super_admin')) return 'developer';
  if (roles.some(role => ['agent', 'managing_broker', 'lead_agent', 'admin', 'super_admin', 'moderator', 'assistant', 'junior_agent'].includes(role))) return 'broker';
  if (roles.includes('affiliate') && !roles.some(role => ['property_owner', 'property_seeker', 'user'].includes(role))) return 'partner';
  return 'private';
}

