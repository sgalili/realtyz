export function findPageTour(pathname: string): PageTourDefinition | undefined {
  // Exact matches first.
  const exact = PAGE_TOURS.find((t) => !t.prefixMatch && t.path === pathname);
  if (exact) return exact;
  // Prefix matches — prefer the most specific (longest path).
  const prefixMatches = PAGE_TOURS.filter((t) => t.prefixMatch && pathname.startsWith(t.path));
  prefixMatches.sort((a, b) => b.path.length - a.path.length);
  return prefixMatches[0];
}

export function listPageTourPaths(): string[] {
  return PAGE_TOURS.map((t) => t.path);
}
