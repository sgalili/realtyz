/** Pick the most specific FAQ set for the user's verified roles. */
export function faqRoleFor(roles: AppRole[]): FaqRoleKey | null {
  if (!roles.length) return null;
  if (roles.includes('developer')) return 'developer';
  if (
    roles.includes('managing_broker') ||
    roles.includes('lead_agent') ||
    roles.includes('agent') ||
    roles.includes('assistant') ||
    roles.includes('junior_agent') ||
    roles.includes('admin') ||
    roles.includes('super_admin')
  ) {
    return 'broker';
  }
  if (roles.includes('affiliate')) return 'affiliate';
  if (roles.includes('property_owner') || roles.includes('property_seeker') || roles.includes('user')) return 'private';
  return 'private';
}

