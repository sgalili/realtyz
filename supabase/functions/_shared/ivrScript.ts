export function cleanIvrScript(text: string): string {
  return text
    .replace(/(?:\p{Extended_Pictographic}|\p{Regional_Indicator}|[0-9#*]\uFE0F?\u20E3)[\uFE0F\u200D\p{Emoji_Modifier}]*/gu, '')
    .split('\n')
    .filter(line => !/רישיון\s*תיווך|מספר\s*רישיון|^\s*(?:טלפון|לפרטים ולתיאום ביקור)\s*[:：]/.test(line))
    .join(' ')
    .replace(/https?:\/\/\S+/gi, '')
    .replace(/[#*_`|•]+/g, '')
    .replace(/[—–]|--+/g, ', ')
    .replace(/\s+/g, ' ')
    .trim();
}